import { t } from "@lingui/core/macro";
import { useMutation, useQuery, useQueryClient } from "@tanstack/react-query";
import { useMemo, useState } from "react";
import { Dialog, DialogContent, DialogHeader, DialogTitle } from "@/components/ui/dialog";
import { orpc } from "@/integrations/orpc/client";
import { cn } from "@/utils/style";
import { getScoreColor } from "./score-helpers";

type EvaluationFormProps = {
	resumeId: string;
	studentId: string;
	tenantId: string;
	open: boolean;
	onOpenChange: (open: boolean) => void;
};

type ItemScore = {
	checklistItemId: string;
	passed: boolean;
	score: number;
	notes: string;
};

export function EvaluationForm({ resumeId, studentId, tenantId, open, onOpenChange }: EvaluationFormProps) {
	const queryClient = useQueryClient();
	const [selectedChecklistId, setSelectedChecklistId] = useState<string | null>(null);
	const [itemScores, setItemScores] = useState<Map<string, ItemScore>>(new Map());

	const { data: checklists } = useQuery(
		orpc.resume.checklists.list.queryOptions({
			input: { tenantId },
		}),
	);

	// When a checklist has items, we need to fetch them — for now we initialize from the list
	// The checklist list endpoint returns id+title; we initialize scores when selected

	const overallScore = useMemo(() => {
		const scores = Array.from(itemScores.values());
		if (scores.length === 0) return null;
		const total = scores.reduce((sum, s) => sum + s.score, 0);
		return total / scores.length;
	}, [itemScores]);

	const createMutation = useMutation(
		orpc.resume.evaluations.create.mutationOptions({
			onSuccess: () => {
				setItemScores(new Map());
				setSelectedChecklistId(null);
				onOpenChange(false);
				queryClient.invalidateQueries({ queryKey: ["resume", "dashboard"] });
			},
		}),
	);

	const handleSubmit = () => {
		if (!selectedChecklistId || itemScores.size === 0) return;

		createMutation.mutate({
			resumeId,
			studentId,
			checklistId: selectedChecklistId,
			tenantId,
			isAutoGenerated: false,
			items: Array.from(itemScores.values()).map((s) => ({
				checklistItemId: s.checklistItemId,
				passed: s.passed,
				score: s.score,
				notes: s.notes || undefined,
			})),
		});
	};

	const updateItemScore = (itemId: string, updates: Partial<ItemScore>) => {
		setItemScores((prev) => {
			const next = new Map(prev);
			const existing = next.get(itemId) ?? { checklistItemId: itemId, passed: false, score: 0, notes: "" };
			next.set(itemId, { ...existing, ...updates });
			return next;
		});
	};

	return (
		<Dialog open={open} onOpenChange={onOpenChange}>
			<DialogContent className="rounded-3xl sm:max-w-[700px]">
				<DialogHeader>
					<DialogTitle className="font-semibold text-lg text-slate-900">{t`Evaluate Resume`}</DialogTitle>
				</DialogHeader>

				{/* Checklist Selector */}
				<div className="space-y-4">
					<div>
						<p className="mb-2 font-semibold text-slate-400 text-xs uppercase tracking-widest">Select Checklist</p>
						<div className="flex flex-wrap gap-2">
							{checklists?.map((cl) => (
								<button
									key={cl.id}
									type="button"
									onClick={() => setSelectedChecklistId(cl.id)}
									className={cn(
										"rounded-xl px-4 py-2 font-semibold text-sm transition-all active:scale-[0.97]",
										selectedChecklistId === cl.id
											? "bg-indigo-600 text-white"
											: "bg-slate-100 text-slate-600 hover:bg-slate-200",
									)}
								>
									{cl.title}
								</button>
							))}
							{!checklists?.length && (
								<p className="text-slate-400 text-sm">No checklists available. Create one first.</p>
							)}
						</div>
					</div>

					{/* Scoring Area */}
					{selectedChecklistId && (
						<div className="space-y-3">
							<p className="font-semibold text-slate-400 text-xs uppercase tracking-widest">Score each item (0-5)</p>

							{/* Since we only have id+title from the list endpoint, we render a simple scoring interface */}
							{/* In a full implementation, we'd fetch checklist items by ID */}
							<div className="rounded-2xl bg-slate-50 p-4">
								<p className="mb-3 text-slate-600 text-sm">
									Enter scores for each evaluation criterion. Use the add button to add items.
								</p>

								{Array.from(itemScores.entries()).map(([itemId, score]) => (
									<div key={itemId} className="mb-3 flex items-center gap-3">
										<input
											type="text"
											value={score.notes}
											onChange={(e) => updateItemScore(itemId, { notes: e.target.value })}
											placeholder="Item description..."
											className="flex-1 rounded-xl border-0 bg-white px-3 py-2 text-sm outline-none ring-1 ring-slate-200 focus:ring-2 focus:ring-indigo-500"
										/>
										<div className="flex items-center gap-2">
											<button
												type="button"
												onClick={() => updateItemScore(itemId, { passed: !score.passed })}
												className={cn(
													"rounded-xl px-3 py-2 font-semibold text-xs transition-all active:scale-[0.97]",
													score.passed ? "bg-emerald-100 text-emerald-700" : "bg-red-100 text-red-700",
												)}
											>
												{score.passed ? "Pass" : "Fail"}
											</button>
											<input
												type="number"
												min={0}
												max={5}
												step={0.5}
												value={score.score}
												onChange={(e) =>
													updateItemScore(itemId, {
														score: Math.min(5, Math.max(0, Number.parseFloat(e.target.value) || 0)),
													})
												}
												className="w-16 rounded-xl border-0 bg-white px-2 py-2 text-center text-sm outline-none ring-1 ring-slate-200 focus:ring-2 focus:ring-indigo-500"
											/>
										</div>
									</div>
								))}

								<button
									type="button"
									onClick={() => {
										const id = crypto.randomUUID();
										updateItemScore(id, { checklistItemId: id, passed: false, score: 0, notes: "" });
									}}
									className="mt-2 rounded-xl bg-white px-4 py-2 font-semibold text-slate-600 text-xs ring-1 ring-slate-200 transition-all hover:bg-slate-50 active:scale-[0.97]"
								>
									+ Add Item
								</button>
							</div>
						</div>
					)}

					{/* Overall Score Preview */}
					{overallScore !== null && (
						<div className="flex items-center justify-between rounded-2xl bg-white p-4 shadow-sm">
							<span className="font-semibold text-slate-900 text-sm">Overall Score</span>
							<span className={cn("font-bold text-2xl", getScoreColor(overallScore))}>{overallScore.toFixed(1)}/5</span>
						</div>
					)}

					{/* Submit */}
					<button
						type="button"
						onClick={handleSubmit}
						disabled={!selectedChecklistId || itemScores.size === 0 || createMutation.isPending}
						className="w-full rounded-xl bg-emerald-600 py-2.5 font-semibold text-sm text-white transition-all hover:bg-emerald-700 active:scale-[0.98] disabled:opacity-50"
					>
						{createMutation.isPending ? "Submitting..." : "Submit Evaluation"}
					</button>
				</div>
			</DialogContent>
		</Dialog>
	);
}
